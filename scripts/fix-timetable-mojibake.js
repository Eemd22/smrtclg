// هل يبدو النص مشوهاً (يحوي محارف ترميز أحادي البايت أو رسم صناديق)؟
function looksMojibake(v) {
  return typeof v === "string" && /[\u0080-\u00FF\u2500-\u25FF]/.test(v);
}

function decodeMojibake(value) {
  const bytes = [];
  for (const ch of value) {
    const mapped = CHAR_MAP[ch];
    if (mapped !== undefined) bytes.push(mapped);
    else if (ch.codePointAt(0) < 0x80) bytes.push(ch.codePointAt(0));
    else return null;
  }
  try {
    const decoded = Buffer.from(bytes).toString("utf8");
    return /[\u0600-\u06FF]/.test(decoded) ? decoded : null;
  } catch (_) {
    return null;
  }
}

function fixColumn(db, table, column) {
  db.query(`SELECT id, ${column} AS v FROM ${table}`, (err, rows) => {
    if (err) return console.error(`Timetable mojibake fix (${table}):`, err.message);
    rows.forEach((row) => {
      if (!looksMojibake(row.v)) return;
      const fixed = MOJIBAKE_MAP[row.v] || decodeMojibake(row.v);
      if (!fixed || fixed === row.v) return;
      db.query(
        `UPDATE ${table} SET ${column} = ? WHERE id = ?`,
        [fixed, row.id],
        (uErr) => {
          if (uErr) return console.error(`Timetable mojibake fix ${table}#${row.id}:`, uErr.message);
          console.log(`Timetable mojibake fixed ${table}#${row.id}: "${row.v}" -> "${fixed}"`);
        }
      );
    });
  });
}

// دمج الأقسام المتطابقة الاسم بعد فكّ الترميز (يبقى الأقدم id أصغر)
function mergeDuplicateDepartments(db) {
  db.query("SELECT id, name FROM departments ORDER BY id", (err, rows) => {
    if (err) return console.error("Departments merge failed:", err.message);
    const byName = new Map();
    for (const row of rows) {
      const key = (row.name || "").trim();
      if (!key) continue;
      if (!byName.has(key)) byName.set(key, row.id);
      else mergeInto(db, byName.get(key), row.id);
    }
  });
}

function mergeInto(db, keepId, dupId) {
  const refTables = [
    ["users", "department_id"],
    ["activites", "dept_id"],
    ["albums", "dept_id"],
    ["courses", "department_id"],
    ["lecture", "dept_id"],
    ["lectures", "department_id"],
  ];
  let pending = refTables.length;
  const finish = () => {
    if (--pending > 0) return;
    db.query("DELETE FROM departments WHERE id = ?", [dupId], (dErr) => {
      if (dErr) return console.error(`Departments merge delete #${dupId}:`, dErr.message);
      console.log(`Departments merged #${dupId} -> #${keepId}`);
    });
  };
  refTables.forEach(([table, col]) => {
    db.query(
      `UPDATE IGNORE ${table} SET ${col} = ? WHERE ${col} = ?`,
      [keepId, dupId],
      (uErr) => {
        if (uErr) console.error(`Departments merge ${table}:`, uErr.message);
        finish();
      }
    );
  });
}

